#!/usr/bin/env bash
#
# One-command installer for Creagent (macOS + Linux).
#
#   curl -fsSL https://raw.githubusercontent.com/masonleetompkins/creagent/main/install.sh | bash
#
# What it does:
#   1. Clones (or updates) the repo to ~/.local/share/creagent
#      (skipped when run from inside the repo).
#   2. Installs dependencies and builds the Next.js app.
#   3. macOS: creates ~/Applications/Creagent.app (no sudo).
#      Linux: creates ~/.local/share/applications/creagent.desktop.
#   4. Starts the local server and opens http://127.0.0.1:3000 in your browser.
#
set -euo pipefail

APP_NAME="Creagent"
APP_SLUG="creagent"
APP_ID="com.masonleetompkins.creagent"
PORT="${PORT:-3000}"
REPO_URL="${REPO_URL:-https://github.com/masonleetompkins/creagent}"
INSTALL_ROOT="${INSTALL_ROOT:-$HOME/.local/share}"
APP_DIR="$INSTALL_ROOT/$APP_SLUG"
CONFIG_DIR="$HOME/.config/$APP_SLUG"

log() { printf '%s\n' "$*"; }
fail() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

OS="$(uname -s)"

# --- 1. Dependencies -------------------------------------------------------
command -v node >/dev/null 2>&1 || fail "Node.js 20+ is required: https://nodejs.org"
NODE_MAJOR="$(node -p 'process.versions.node.split(".")[0]')"
[ "$NODE_MAJOR" -ge 20 ] || fail "Node 20+ is required (found $(node --version))"
command -v npm >/dev/null 2>&1 || fail "npm is required (ships with Node.js)"

# --- 2. Source -------------------------------------------------------------
if [ -f "./package.json" ] && grep -q '"creagent"' ./package.json 2>/dev/null; then
  APP_DIR="$PWD"
  log "Installing from current directory: $APP_DIR"
else
  command -v git >/dev/null 2>&1 || fail "git is required for a fresh install"
  if [ -d "$APP_DIR/.git" ]; then
    log "Updating existing install at $APP_DIR"
    git -C "$APP_DIR" pull --ff-only
  else
    log "Cloning $REPO_URL into $APP_DIR"
    mkdir -p "$INSTALL_ROOT"
    git clone "$REPO_URL" "$APP_DIR"
  fi
fi

cd "$APP_DIR"
mkdir -p "$CONFIG_DIR"

log "Installing dependencies…"
if [ -f package-lock.json ]; then
  npm ci --no-audit --no-fund
else
  npm install --no-audit --no-fund
fi

log "Building…"
npm run build

log "Ensuring video tools (ffmpeg, whisper)…"
"$APP_DIR/scripts/ensure-tools.sh"

# --- 3. Start / stop scripts -----------------------------------------------
NODE_BIN_DIR="$(dirname "$(command -v npx)")"
cat > "$APP_DIR/start.sh" <<EOF
#!/usr/bin/env bash
# Generated by install.sh — starts the local server and opens the app.
set -euo pipefail
PORT="\${PORT:-$PORT}"
APP_DIR="$APP_DIR"
CONFIG_DIR="$CONFIG_DIR"
# Finder-launched apps get a minimal PATH; restore the Node toolchain.
export PATH="$NODE_BIN_DIR:\$PATH:/opt/homebrew/bin:/usr/local/bin"
mkdir -p "\$CONFIG_DIR"
# Mirror all launcher output to a log (Finder launches show no terminal).
exec > >(tee -a "\$CONFIG_DIR/launcher.log") 2>&1
echo "=== \$(date '+%F %T') launcher start (port \$PORT) ==="
cd "\$APP_DIR"
("\$APP_DIR/scripts/ensure-tools.sh") || echo "WARNING: video tools are incomplete."
(cd "\$APP_DIR" && npx tsx scripts/migrate.ts) || echo "WARNING: migrations did not complete."
URL="http://127.0.0.1:\$PORT"

running_build() {
  curl -sf -m 3 "\$URL/api/health" 2>/dev/null | grep -o '"buildId":"[^"]*"' | cut -d'"' -f4
}
current_build() { cat "\$APP_DIR/.next/BUILD_ID" 2>/dev/null || echo "dev"; }
# A pid belongs to this app if its command mentions the repo or its cwd is the repo.
is_creagent_pid() {
  [ -n "\${1:-}" ] || return 1
  local cmd cwd
  cmd="\$(ps -p "\$1" -o command= 2>/dev/null || true)"
  [ -n "\$cmd" ] || return 1
  case "\$cmd" in *creagent*) return 0;; esac
  command -v lsof >/dev/null 2>&1 || return 1
  cwd="\$(lsof -a -p "\$1" -d cwd -Fn 2>/dev/null | sed -n 's/^n//p' || true)"
  [ "\$cwd" = "\$APP_DIR" ]
}
port_busy() {
  if command -v lsof >/dev/null 2>&1; then
    [ -n "\$(lsof -ti ":\$PORT" 2>/dev/null || true)" ]
  else
    curl -sf -m 2 "\$URL/" -o /dev/null 2>&1
  fi
}
# Kill only Creagent processes on our port; never touch foreign listeners.
kill_port() {
  command -v lsof >/dev/null 2>&1 || return 0
  local pids pid cmd
  pids="\$(lsof -ti ":\$PORT" 2>/dev/null || true)"
  echo "port \$PORT holders: \${pids:-none}"
  for pid in \$pids; do
    cmd="\$(ps -p "\$pid" -o command= 2>/dev/null || true)"
    echo "holder \$pid: \$cmd"
    if is_creagent_pid "\$pid"; then kill "\$pid" 2>/dev/null || true
    else echo "NOT killing non-Creagent process \$pid"; fi
  done
  sleep 2
  # Escalate: SIGKILL Creagent holders that ignored SIGTERM.
  pids="\$(lsof -ti ":\$PORT" 2>/dev/null || true)"
  for pid in \$pids; do
    if is_creagent_pid "\$pid"; then
      echo "holder \$pid survived SIGTERM; SIGKILLing"
      kill -9 "\$pid" 2>/dev/null || true
    fi
  done
  sleep 1
}
stop_worker() {
  if [ -f "\$CONFIG_DIR/worker.pid" ]; then
    kill "\$(cat "\$CONFIG_DIR/worker.pid")" 2>/dev/null || true
    rm -f "\$CONFIG_DIR/worker.pid"
  fi
  sleep 1
  # Sweep survivors: the tsx child outlives the npx parent, so pidfile kills
  # leak workers that keep polling with old code. Kill all survivors by cwd.
  local pid cmd
  for pid in \$(ps aux 2>/dev/null | grep "[w]orker.ts" | awk '{print \$2}'); do
    cmd="\$(ps -p "\$pid" -o command= 2>/dev/null || true)"
    case "\$cmd" in *node*|*tsx*|*deno*|*bun*) ;; *) continue ;; esac
    if is_creagent_pid "\$pid"; then kill "\$pid" 2>/dev/null || true; fi
  done
  sleep 2
  for pid in \$(ps aux 2>/dev/null | grep "[w]orker.ts" | awk '{print \$2}'); do
    cmd="\$(ps -p "\$pid" -o command= 2>/dev/null || true)"
    case "\$cmd" in *node*|*tsx*|*deno*|*bun*) ;; *) continue ;; esac
    if is_creagent_pid "\$pid"; then kill -9 "\$pid" 2>/dev/null || true; fi
  done
}

RUNNING="\$(running_build || true)"
CURRENT="\$(current_build)"
RECORDED="\$(cat "\$CONFIG_DIR/server.build" 2>/dev/null || echo "")"
RECORDED_PID="\$(cat "\$CONFIG_DIR/server.pid" 2>/dev/null || echo "")"
echo "running build: \${RUNNING:-none}, started build: \${RECORDED:-none}, current build: \$CURRENT"
# The recorded started-build is authoritative: it proves this launcher
# started the live pid from the on-disk build. (Health's buildId comes from
# the running process, so a stale server can no longer impersonate a new one.)
server_fresh() {
  [ -n "\$RUNNING" ] && [ "\$RUNNING" = "\$CURRENT" ] || return 1
  if command -v lsof >/dev/null 2>&1; then
    [ "\$RECORDED" = "\$CURRENT" ] && is_creagent_pid "\$RECORDED_PID"
  else
    return 0
  fi
}
if server_fresh; then
  echo "Server already running on the current build. Opening browser…"
else
  if [ -n "\$RUNNING" ]; then
    echo "Server is on an old build (\$RUNNING vs \$CURRENT). Restarting…"
  elif port_busy; then
    echo "Port \$PORT is busy with an unrecognized server. Restarting…"
  else
    echo "Port \$PORT is free. Starting fresh…"
  fi
  kill_port
  rm -f "\$CONFIG_DIR/server.pid" "\$CONFIG_DIR/server.build"
  stop_worker
  echo "Starting server on port \${PORT}..."
  nohup npx next start -H 127.0.0.1 -p "\$PORT" >>"\$CONFIG_DIR/server.log" 2>&1 &
  echo \$! > "\$CONFIG_DIR/server.pid"
  echo "\$CURRENT" > "\$CONFIG_DIR/server.build"
  echo "Starting worker..."
  nohup npx tsx worker.ts >>"\$CONFIG_DIR/worker.log" 2>&1 &
  echo \$! > "\$CONFIG_DIR/worker.pid"
  echo "Waiting for server…"
  for _ in \$(seq 1 60); do
    HB="\$(running_build || true)"
    if [ "\$HB" = "\$CURRENT" ]; then break; fi
    sleep 2
  done
  HB="\$(running_build || true)"
  if [ "\$HB" != "\$CURRENT" ]; then
    echo "ERROR: port \$PORT answers with build '\${HB:-none}', not \$CURRENT. A foreign server may own the port."
  fi
fi
# Cache-buster so the browser never renders a cached page from an older build.
OPEN_URL="\$URL/?v=\$CURRENT"
if command -v open >/dev/null 2>&1; then open "\$OPEN_URL" || true;
elif command -v xdg-open >/dev/null 2>&1; then xdg-open "\$OPEN_URL" >/dev/null 2>&1 & disown;
else echo "Open \$OPEN_URL in your browser."; fi
EOF
chmod +x "$APP_DIR/start.sh"

cat > "$APP_DIR/stop.sh" <<EOF
#!/usr/bin/env bash
# Generated by install.sh — stops the local server.
set -euo pipefail
PORT="\${PORT:-$PORT}"
CONFIG_DIR="$CONFIG_DIR"
stopped=0
if [ -f "\$CONFIG_DIR/server.pid" ]; then
  if kill "\$(cat "\$CONFIG_DIR/server.pid")" 2>/dev/null; then
    echo "Server stopped."
    stopped=1
  fi
  rm -f "\$CONFIG_DIR/server.pid" "\$CONFIG_DIR/server.build"
fi
if [ -f "\$CONFIG_DIR/worker.pid" ]; then
  if kill "\$(cat "\$CONFIG_DIR/worker.pid")" 2>/dev/null; then
    echo "Worker stopped."
    stopped=1
  fi
  rm -f "\$CONFIG_DIR/worker.pid"
fi
# Fallback: a server that outlived its pid file still holds the port.
if command -v lsof >/dev/null 2>&1; then
  for pid in \$(lsof -ti ":\$PORT" 2>/dev/null || true); do
    cmd="\$(ps -p "\$pid" -o command= 2>/dev/null || true)"
    case "\$cmd" in
      *creagent*)
        if kill "\$pid" 2>/dev/null; then
          echo "Server stopped (found on port \$PORT)."
          stopped=1
        fi
        ;;
    esac
  done
fi
# Sweep leaked workers: the tsx child outlives the npx parent, so it
# never appears in worker.pid. Match by command + repo path only.
for pid in \$(ps aux 2>/dev/null | grep "[w]orker.ts" | awk '{print \$2}'); do
  cmd="\$(ps -p "\$pid" -o command= 2>/dev/null || true)"
  case "\$cmd" in *node*|*tsx*|*deno*|*bun*) ;; *) continue ;; esac
  case "\$cmd" in
    *creagent*)
      if kill -9 "\$pid" 2>/dev/null; then
        echo "Worker stopped (leaked process \$pid)."
        stopped=1
      fi
      ;;
  esac
done
if [ "\$stopped" = "0" ]; then
  echo "Server was not running."
fi
EOF
chmod +x "$APP_DIR/stop.sh"

# --- 4. OS launcher ---------------------------------------------------------
if [ "$OS" = "Darwin" ]; then
  BUNDLE="$HOME/Applications/$APP_NAME.app"
  log "Creating $BUNDLE"
  mkdir -p "$BUNDLE/Contents/MacOS" "$BUNDLE/Contents/Resources"
  if [ -f "$APP_DIR/assets/Creagent.icns" ]; then
    cp "$APP_DIR/assets/Creagent.icns" "$BUNDLE/Contents/Resources/"
  else
    log "WARNING: assets/Creagent.icns missing, bundle will have no icon."
  fi
  cat > "$BUNDLE/Contents/Info.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key>
  <string>$APP_NAME</string>
  <key>CFBundleDisplayName</key>
  <string>$APP_NAME</string>
  <key>CFBundleIdentifier</key>
  <string>$APP_ID</string>
  <key>CFBundleVersion</key>
  <string>0.1.0</string>
  <key>CFBundlePackageType</key>
  <string>APPL</string>
  <key>CFBundleExecutable</key>
  <string>launcher</string>
  <key>CFBundleIconFile</key>
  <string>Creagent</string>
  <key>LSMinimumSystemVersion</key>
  <string>12.0</string>
</dict>
</plist>
EOF
  printf '#!/bin/bash\nexec "%s/start.sh"\n' "$APP_DIR" > "$BUNDLE/Contents/MacOS/launcher"
  chmod +x "$BUNDLE/Contents/MacOS/launcher"
  xattr -cr "$BUNDLE" 2>/dev/null || true
  log "Done. Launch \"$APP_NAME\" from ~/Applications (Spotlight works too)."
elif [ "$OS" = "Linux" ]; then
  DESKTOP="$HOME/.local/share/applications/$APP_SLUG.desktop"
  log "Creating $DESKTOP"
  mkdir -p "$(dirname "$DESKTOP")"
  cat > "$DESKTOP" <<EOF
[Desktop Entry]
Name=$APP_NAME
Comment=Local-first agentic content creation
Exec=$APP_DIR/start.sh
Type=Application
Terminal=false
Categories=Utility;
EOF
  if command -v update-desktop-database >/dev/null 2>&1; then
    update-desktop-database "$(dirname "$DESKTOP")" >/dev/null 2>&1 || true
  fi
  log "Done. Launch \"$APP_NAME\" from your app menu."
else
  log "Unknown OS ($OS): skipping launcher. Use $APP_DIR/start.sh directly."
fi

# --- 5. Start now ------------------------------------------------------------
"$APP_DIR/start.sh"
